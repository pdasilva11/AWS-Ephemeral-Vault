"""
Registrar -- CloudFormation Custom Resource that welds the Password Safe
managed account to the EC2 instance lifecycle.

  Create  -> wait for SSM readiness, read the per-instance SSH key
             AWS::EC2::KeyPair generated (environment.yaml), install its
             public half over SSM Run Command, onboard asset + managed
             system + managed account (carrying the private half), force an
             immediate rotation, reprocess both Smart Rules.
  Update  -> rotate + reprocess. Ids are stable.
  Delete  -> delete managed account and asset, reprocess. Idempotent; a
             missing object is success, not failure.

Why the key is read here rather than passed in from CloudFormation as a
plain value: a CFN parameter is visible in the console, in
`describe-stacks`, in the change set and in CloudTrail. AWS::EC2::KeyPair
instead stores the private half as an SSM SecureString that only this
function's role can decrypt; the only place the plaintext private key ever
exists is in this function's memory, briefly, en route to Password Safe.
After the first rotation (DSSAutoManagementFlag=true), even that seed key is
stale -- every key after it is generated by Password Safe itself.

DELETE MUST NOT THROW. A Custom Resource that fails on Delete leaves the
stack in DELETE_FAILED and a human has to go clean it up by hand. Every
failure on that path is logged and swallowed; orphan detection is the job of
scripts/reconcile.py, not of stack teardown.
"""

import json
import logging
import os
import time
import urllib.request
import secrets
import string

import boto3

import ec2_keypair
from passwordsafe import PasswordSafeClient, PasswordSafeError
from ssh_pubkey import openssh_public_key, KeyParseError

log = logging.getLogger()
log.setLevel(logging.INFO)

ssm = boto3.client("ssm")
secretsmanager = boto3.client("secretsmanager")

PS_BASE_URL = os.environ["PS_BASE_URL"]
PS_SECRET_ARN = os.environ["PS_SECRET_ARN"]

# Holds the functional account's PRIVATE key. Optional: if unset, the
# functional account must already exist in Password Safe and the registrar
# will only look it up, never create it.
PS_FUNCTIONAL_SECRET_ARN = os.environ.get("PS_FUNCTIONAL_SECRET_ARN") or None
FUNCTIONAL_PUBKEY_PARAM = os.environ.get(
    "FUNCTIONAL_PUBKEY_PARAM", "/ps-ephemeral/functional-account/public-key")

SSM_READY_TIMEOUT = int(os.environ.get("SSM_READY_TIMEOUT", "300"))
SSM_POLL_INTERVAL = 10
CMD_TIMEOUT = 120

CREATE_FAILED_SENTINEL = "CREATE_FAILED"


