# helpers
# --------------------------------------------------------------------------- #
def load_ps_credentials():
    """Bootstrap secret: the ONLY standing privilege in the whole design."""
    raw = secretsmanager.get_secret_value(SecretId=PS_SECRET_ARN)["SecretString"]
    doc = json.loads(raw)
    return doc["client_id"], doc["client_secret"]


def load_functional_credential():
    """
    Private half of the functional account's SSH key. Returns {} if no
    secret is configured, OR if the configured secret does not exist --
    in either case the functional account must already exist in Password
    Safe. ensure_functional_account() looks it up by name first and only
    needs these values on the create path, so a missing secret here is
    only fatal if the account also turns out not to exist.
    """
    if not PS_FUNCTIONAL_SECRET_ARN:
        return {}
    try:
        raw = secretsmanager.get_secret_value(
            SecretId=PS_FUNCTIONAL_SECRET_ARN)["SecretString"]
    except secretsmanager.exceptions.ResourceNotFoundException:
        log.info("functional account secret %s not found -- assuming the "
                  "functional account already exists in Password Safe",
                  PS_FUNCTIONAL_SECRET_ARN)
        return {}
    doc = json.loads(raw)
    return {
        "private_key": doc.get("private_key"),
        "passphrase": doc.get("passphrase"),
        "password": doc.get("password"),
    }


def read_public_key():
    """Public keys are not secrets, so this is a plain String parameter."""
    try:
        return ssm.get_parameter(Name=FUNCTIONAL_PUBKEY_PARAM)["Parameter"]["Value"]
    except ssm.exceptions.ParameterNotFound:
        return None


def generate_random_password(length=32):
    """Generate a secure random password for password-auth accounts."""
    alphabet = string.ascii_letters + string.digits + "!@#$%^&*"
    return ''.join(secrets.choice(alphabet) for _ in range(length))


def wait_for_ssm(instance_id):
    """
    The real readiness gate. DependsOn only tells you the RunInstances API
    returned -- it says nothing about whether the box has booted. If we onboard
    before the host answers, the Password Safe test-connection fails and we
    would hand the team an account they cannot use.
    """
    deadline = time.time() + SSM_READY_TIMEOUT
    while time.time() < deadline:
        resp = ssm.describe_instance_information(
            Filters=[{"Key": "InstanceIds", "Values": [instance_id]}]
        )
        info = resp.get("InstanceInformationList", [])
        if info and info[0].get("PingStatus") == "Online":
            log.info("instance %s online in SSM", instance_id)
            return
        time.sleep(SSM_POLL_INTERVAL)
    raise TimeoutError(
        f"{instance_id} did not register with SSM within {SSM_READY_TIMEOUT}s"
    )


def run_command(instance_id, commands):
    cmd = ssm.send_command(
        InstanceIds=[instance_id],
        DocumentName="AWS-RunShellScript",
        Parameters={"commands": commands},
        TimeoutSeconds=CMD_TIMEOUT,
    )["Command"]["CommandId"]

    deadline = time.time() + CMD_TIMEOUT
    while time.time() < deadline:
        time.sleep(3)
        try:
            inv = ssm.get_command_invocation(
                CommandId=cmd, InstanceId=instance_id
            )
        except ssm.exceptions.InvocationDoesNotExist:
            continue
        if inv["Status"] in ("Success",):
            return inv
        if inv["Status"] in ("Failed", "Cancelled", "TimedOut"):
            # StandardErrorContent is safe to log: the password goes in via
            # stdin heredoc and is never echoed by chpasswd.
            raise RuntimeError(
                f"SSM command {inv['Status']}: {inv.get('StandardErrorContent','')[:500]}"
            )
    raise TimeoutError(f"SSM command {cmd} did not finish in {CMD_TIMEOUT}s")


def provision_functional_account(instance_id, username, public_key,
                                 elevation="sudo"):
    """
    Create the functional account ON THE INSTANCE and install the public half
    of the key whose private half lives in Password Safe.

    user-data already does this at boot; doing it again here is deliberate.
    user-data is best-effort and silent when it fails, and if this account is
    missing or its key is wrong then the very first rotation fails -- leaving a
    vaulted credential that does not actually work. Better to converge it now,
    synchronously, while we can still fail the stack.

    Sudo is restricted to the two binaries a password change needs. Full
    NOPASSWD:ALL would make this account a fleet-wide root equivalent.
    """
    script = [
        "set -euo pipefail",
        f"id -u {username} >/dev/null 2>&1 || useradd -m -s /bin/bash {username}",
        f"install -d -m 700 -o {username} -g {username} /home/{username}/.ssh",
        f"cat > /home/{username}/.ssh/authorized_keys <<'PUBKEY'",
        public_key,
        "PUBKEY",
        f"chown {username}:{username} /home/{username}/.ssh/authorized_keys",
        f"chmod 600 /home/{username}/.ssh/authorized_keys",
        f"cat > /etc/sudoers.d/90-{username} <<'SUDO'",
        # grep/sed/tee are BeyondTrust's own documented requirement for the
        # functional account: SSH key auto-management removes the old public
        # key from authorized_keys (grep/sed) and appends the new one (tee).
        # chpasswd/passwd alone is only enough for PASSWORD rotation.
        f"{username} ALL=(root) NOPASSWD: /usr/sbin/chpasswd, /usr/bin/passwd, "
        f"/usr/bin/grep, /usr/bin/sed, /usr/bin/tee",
        "SUDO",
        f"chmod 440 /etc/sudoers.d/90-{username}",
        "visudo -c >/dev/null",
        # Fail loudly here rather than at first rotation.
        f"test -s /home/{username}/.ssh/authorized_keys",
    ]
    run_command(instance_id, script)
    log.info("functional account %s converged on %s", username, instance_id)


def provision_local_account_with_key(instance_id, username, public_key):
    """
    Create (or converge) the managed account itself and install the public
    half of a key AWS generated -- see environment.yaml's per-instance
    AWS::EC2::KeyPair. The private half went from SSM straight into this
    function's caller and then into the Password Safe API call; it is never
    written to disk, a template, or an instance.

    No special sudo for this account -- it is the account BEING managed, not
    an elevation identity. Password Safe writes this account's *next* key
    into this same file by logging in as the functional account and
    elevating with ITS sudo rule (provision_functional_account), not this
    one. If that elevation rule turns out to be too narrow for Linux DSS key
    rotation, that shows up here, not on this account.
    """
    script = [
        "set -euo pipefail",
        f"id -u {username} >/dev/null 2>&1 || useradd -m -s /bin/bash {username}",
        f"install -d -m 700 -o {username} -g {username} /home/{username}/.ssh",
        f"cat > /home/{username}/.ssh/authorized_keys <<'PUBKEY'",
        public_key,
        "PUBKEY",
        f"chown {username}:{username} /home/{username}/.ssh/authorized_keys",
        f"chmod 600 /home/{username}/.ssh/authorized_keys",
        # Key auth only for this account -- there is no password to fall
        # back to, so leaving password auth on would just be an unused,
        # unaudited second door.
        f"passwd -l {username} >/dev/null 2>&1 || true",
        f"test -s /home/{username}/.ssh/authorized_keys",
    ]
    run_command(instance_id, script)
    log.info("managed account %s key-provisioned on %s", username, instance_id)


def provision_local_account_with_password(instance_id, username, password):
    """
    Create (or converge) the managed account with password authentication.
    Password Safe will manage the password lifecycle via rotation.
    
    Enables SSH password authentication in sshd_config and sets the password
    via chpasswd (which never echoes the password to stdout/stderr).
    """
    script = [
        "set -euo pipefail",
        f"id -u {username} >/dev/null 2>&1 || useradd -m -s /bin/bash {username}",
        # Set password securely via stdin
        f"echo '{username}:{password}' | chpasswd",
        # Enable password authentication in SSH
        "sed -i 's/^PasswordAuthentication no/PasswordAuthentication yes/' /etc/ssh/sshd_config || true",
        "sed -i 's/^#PasswordAuthentication yes/PasswordAuthentication yes/' /etc/ssh/sshd_config || true",
        # Ensure PubkeyAuthentication is still on (for other accounts)
        "sed -i 's/^PubkeyAuthentication no/PubkeyAuthentication yes/' /etc/ssh/sshd_config || true",
        "systemctl restart sshd",
        # Verify account exists
        f"id -u {username} >/dev/null",
    ]
    run_command(instance_id, script)
    log.info("managed account %s password-provisioned on %s", username, instance_id)


def reprocess_rules(ps, cfg):
    """Best-effort: a rule that will not reprocess must not fail the stack."""
    for title in (cfg.get("smartRuleSystems"), cfg.get("smartRuleAccounts")):
        if not title:
            continue
        try:
            rule = ps.find_smart_rule(title)
            if rule:
                ps.process_smart_rule(rule["SmartRuleID"])
                log.info("reprocessed smart rule %s", title)
            else:
                log.warning("smart rule %r not found -- team will not see this "
                            "host until it exists", title)
        except PasswordSafeError as exc:
            log.warning("smart rule %s reprocess failed: %s", title, exc)


